using System.Globalization;
using System.Text;
using PowerQueryDocumenter.Core.Model;

namespace PowerQueryDocumenter.Core.Export;

/// <summary>
/// Builds PlantUML source for a dependency graph (FR-PUML-1 to FR-PUML-3). Every query becomes a
/// node with a deterministic alias (q1, q2, ... in name order) and its real name as an escaped
/// display label, so names with spaces, quotes or markup characters cannot break the diagram.
/// </summary>
public static class PlantUmlDiagramBuilder
{
  /// <summary>Fill colours per role, shared with the legend.</summary>
  public const string RootColour = "#D5E8D4";

  /// <summary>Leaf fill colour.</summary>
  public const string LeafColour = "#DAE8FC";

  /// <summary>Intermediate fill colour.</summary>
  public const string IntermediateColour = "#F5F5F5";

  /// <summary>Isolated fill colour.</summary>
  public const string IsolatedColour = "#FFFFFF";

  /// <summary>In-cycle fill colour.</summary>
  public const string CycleColour = "#F8CECC";

  /// <summary>Colour of arrows inside a circular dependency.</summary>
  public const string CycleArrowColour = "#B85450";

  // Characters PlantUML or its Creole markup can interpret: quotes and escapes, HTML-like tags and
  // entities, preprocessor variables and functions, links, tables, list and heading markers.
  private const string AlwaysEscaped = "\"\\<>&~$%[]{}|`^#*=";

  // Characters that are only markup when doubled ("__underline__", "--strike--", "//italic//").
  private const string EscapedWhenDoubled = "_-/";

  /// <summary>Builds the diagram source. Lines are separated by LF.</summary>
  /// <param name="graph">The dependency graph.</param>
  /// <param name="title">Diagram title (escaped by this method).</param>
  public static string Build(DependencyGraph graph, string title)
  {
    ArgumentNullException.ThrowIfNull(graph);
    ArgumentNullException.ThrowIfNull(title);

    var aliases = CreateAliases(graph);
    var cycleGroupOf = new Dictionary<string, int>(DependencyGraph.NameComparer);
    for (var i = 0; i < graph.Cycles.Count; i++)
    {
      foreach (var member in graph.Cycles[i].Members)
      {
        cycleGroupOf[member] = i;
      }
    }

    var lines = new List<string>
    {
      "@startuml",
      "' Power Query dependency graph generated by pqdoc.",
      "' Arrows run from the referenced (upstream) query to the query that references it (downstream).",
      $"title {EscapeLabel(title)}",
      "left to right direction",
      "skinparam shadowing false",
      "skinparam defaultTextAlignment center",
      "skinparam ArrowColor #555555",
      "skinparam rectangle {",
      "  RoundCorner 10",
      $"  BackgroundColor {IntermediateColour}",
      "  BorderColor #666666",
      $"  BackgroundColor<<root>> {RootColour}",
      "  BorderColor<<root>> #82B366",
      $"  BackgroundColor<<leaf>> {LeafColour}",
      "  BorderColor<<leaf>> #6C8EBF",
      $"  BackgroundColor<<isolated>> {IsolatedColour}",
      "  BorderColor<<isolated>> #999999",
      "  BorderStyle<<isolated>> dashed",
      $"  BackgroundColor<<cycle>> {CycleColour}",
      $"  BorderColor<<cycle>> {CycleArrowColour}",
      "  BorderThickness<<cycle>> 2",
      "}",
      "hide stereotype",
      string.Empty,
    };

    foreach (var node in graph.Nodes)
    {
      var stereotype = Stereotype(node);
      lines.Add($"rectangle \"{EscapeLabel(node.Name)}\" as {aliases[node.Name]}{(stereotype is null ? string.Empty : $" <<{stereotype}>>")}");
    }

    if (graph.Edges.Count > 0)
    {
      lines.Add(string.Empty);
    }

    foreach (var edge in graph.Edges)
    {
      var inSameCycle = cycleGroupOf.TryGetValue(edge.Upstream, out var upstreamGroup)
        && cycleGroupOf.TryGetValue(edge.Downstream, out var downstreamGroup)
        && upstreamGroup == downstreamGroup;
      var arrow = inSameCycle ? $"-[{CycleArrowColour},bold]->" : "-->";
      lines.Add($"{aliases[edge.Upstream]} {arrow} {aliases[edge.Downstream]}");
    }

    lines.AddRange(
    [
      string.Empty,
      "legend right",
      "  |= Colour |= Meaning |",
      $"  |<{RootColour}>      | Root: references no other query |",
      $"  |<{LeafColour}>      | Leaf: not referenced by any query |",
      $"  |<{IntermediateColour}>      | References and is referenced |",
      $"  |<{IsolatedColour}>      | Isolated: no dependencies either way |",
      $"  |<{CycleColour}>      | In a circular dependency (red arrows) |",
      "endlegend",
      "@enduml",
    ]);

    return string.Join('\n', lines) + "\n";
  }

  /// <summary>Assigns aliases q1, q2, ... in node (name) order.</summary>
  public static IReadOnlyDictionary<string, string> CreateAliases(DependencyGraph graph)
  {
    ArgumentNullException.ThrowIfNull(graph);
    var aliases = new Dictionary<string, string>(DependencyGraph.NameComparer);
    for (var i = 0; i < graph.Nodes.Count; i++)
    {
      aliases[graph.Nodes[i].Name] = "q" + (i + 1).ToString(CultureInfo.InvariantCulture);
    }

    return aliases;
  }

  /// <summary>
  /// Escapes text for use inside a double-quoted PlantUML label. Characters that PlantUML could
  /// interpret are written as numeric character references (for example <c>"</c> becomes
  /// <c>&amp;#34;</c>), which PlantUML renders as the original character. Control characters
  /// become spaces.
  /// </summary>
  public static string EscapeLabel(string text)
  {
    ArgumentNullException.ThrowIfNull(text);
    var escaped = new StringBuilder(text.Length + 16);
    Rune? previous = null;

    foreach (var rune in text.EnumerateRunes())
    {
      if (Rune.IsControl(rune))
      {
        escaped.Append(' ');
      }
      else if (rune.IsAscii
        && (AlwaysEscaped.Contains((char)rune.Value, StringComparison.Ordinal)
          || (EscapedWhenDoubled.Contains((char)rune.Value, StringComparison.Ordinal) && previous == rune)))
      {
        escaped.Append("&#").Append(rune.Value.ToString(CultureInfo.InvariantCulture)).Append(';');
      }
      else
      {
        escaped.Append(rune.ToString());
      }

      previous = rune;
    }

    return escaped.ToString();
  }

  private static string? Stereotype(QueryNode node)
  {
    if (node.IsInCycle)
    {
      return "cycle";
    }

    return node.Role switch
    {
      QueryRole.Root => "root",
      QueryRole.Leaf => "leaf",
      QueryRole.Isolated => "isolated",
      _ => null,
    };
  }
}
